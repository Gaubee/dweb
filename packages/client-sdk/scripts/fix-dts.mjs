for (const t of TRANSFORMS) {
  s = t.apply(s);
}
const failed = TRANSFORMS.filter((t) => !t.assertInvariant(s)).map((t) => t.name);
if (failed.length > 0) {
  throw new Error(`fix-dts: 输出不变量失败（未写入）：${failed.join(", ")}`);
}
fs.writeFileSync(p, Buffer.from(s, "utf8"));
